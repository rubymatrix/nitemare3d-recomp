#!/usr/bin/env python3
"""Emit src/gen/rc_data.c: the relocated memory image of NITE3W.EXE segments and
the import table (EXTERNAL block address -> module/name) for the runtime."""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXP = os.path.join(ROOT, 'recomp', 'export')
OUT = os.path.join(ROOT, 'src', 'gen', 'rc_data.c')

memory = json.load(open(os.path.join(EXP, 'memory.json')))
imports = json.load(open(os.path.join(EXP, 'imports.json')))

with open(OUT, 'w') as w:
    w.write('/* Generated by tools/gen_data.py from NITE3W.EXE - do not edit. */\n')
    w.write('#include "rt/rt.h"\n\n')
    segs = []
    for b in memory:
        sel = b['start'] >> 16
        if not (b['name'].startswith('Code') or b['name'].startswith('Data')):
            continue
        name = 'seg_%04x' % sel
        if b['file']:
            data = open(os.path.join(EXP, b['file']), 'rb').read()
            w.write('static const uint8_t %s[%d] = {\n' % (name, len(data)))
            for i in range(0, len(data), 24):
                w.write('  ' + ','.join(str(x) for x in data[i:i + 24]) + ',\n')
            w.write('};\n')
            segs.append((sel, b['size'], name, len(data)))
        else:
            segs.append((sel, b['size'], 'NULL', 0))
    w.write('\nconst rt_segimage_t rt_seg_images[] = {\n')
    for sel, size, name, n in segs:
        w.write('  {0x%04x, %d, %s, %d},\n' % (sel, size, name, n))
    w.write('};\nconst int rt_seg_image_count = %d;\n\n' % len(segs))
    w.write('const rt_import_t rt_imports[] = {\n')
    for i in imports:
        nm = i['name']
        w.write('  {0x%xu, "%s", "%s"},\n' % (i['addr'], i['lib'], nm))
    w.write('};\nconst int rt_import_count = %d;\n' % len(imports))
print('wrote', OUT)
